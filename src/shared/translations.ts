export function createTranslator(language: Language) {
  return (source: string, values: Record<string, string | number> = {}): string => {
    const key = source.trim();
    const translated = language === 'ko' ? (korean[key] ?? key) : key;
    const prefix = source.match(/^\s*/)?.[0] ?? '';
    const suffix = source.match(/\s*$/)?.[0] ?? '';
    return `${prefix}${translated.replace(/\{([^{}]+)\}/g, (match, name: string) => String(values[name] ?? match))}${suffix}`;
  };
}
